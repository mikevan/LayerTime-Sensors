#!/usr/bin/env python3
"""Rebuild the pinned registry snapshots that test_sources checks against.

The IEEE and the Bluetooth SIG publish the official owners of address
prefixes (OUIs), company identifiers, and 16-bit UUIDs. Their own download
sites are not reachable from every build machine, so this reads Wireshark's
generated copies of both registries, which the Wireshark project rebuilds
from the official files every week:

  epan/manuf-data.c                    from standards-oui.ieee.org
  epan/dissectors/data-bluetooth.c     from the Bluetooth SIG assigned numbers

Only the identifiers that src/lts/Signatures.h actually uses are written to
sources/snapshots/, so the snapshots stay small and every line is reviewable.
An identifier the registry does not list is written as UNASSIGNED, so the
snapshot records the absence instead of leaving a gap.

  tools/refresh_registry_snapshots.py                      download (needs github.com)
  tools/refresh_registry_snapshots.py --commit <sha>       download that Wireshark commit
  tools/refresh_registry_snapshots.py --manuf F --bluetooth F --commit <sha>
                                                           use files already downloaded

Standard library only. Run it from any folder.
"""
import argparse
import datetime
import hashlib
import json
import pathlib
import re
import urllib.request

ROOT = pathlib.Path(__file__).resolve().parent.parent
SIGNATURES = ROOT / "src" / "lts" / "Signatures.h"
OUT = ROOT / "sources" / "snapshots"
REPO = "wireshark/wireshark"
MANUF_PATH = "epan/manuf-data.c"
BT_PATH = "epan/dissectors/data-bluetooth.c"


def fetch(url):
    request = urllib.request.Request(url, headers={"User-Agent": "lts-registry-snapshot"})
    with urllib.request.urlopen(request, timeout=60) as response:
        return response.read()


def latest_commit():
    data = json.loads(fetch(f"https://api.github.com/repos/{REPO}/commits?path={MANUF_PATH}&per_page=1"))
    return data[0]["sha"]


def used_identifiers():
    text = SIGNATURES.read_text(encoding="utf-8")
    ouis = sorted({":".join(m) for m in re.findall(
        r"\{\{0x([0-9A-Fa-f]{2}),\s*0x([0-9A-Fa-f]{2}),\s*0x([0-9A-Fa-f]{2})\}", text)})
    ouis = [o.upper() for o in ouis]
    uuid_block = text[text.index("kBleUuidSignatures[] = {"):]
    uuid_block = uuid_block[:uuid_block.index("};")]
    uuids = sorted({u.upper() for u in re.findall(r"\{0x([0-9A-Fa-f]{4}),\s*DetectorId", uuid_block)})
    companies = sorted({c.upper() for c in re.findall(
        r"CompanyId\s*=\s*0x([0-9A-Fa-f]{4})", text)})
    return ouis, uuids, companies


def parse_manuf(text):
    blocks, owners = {}, {}
    for a, b, c, kind in re.findall(
            r"\{ \{ 0x([0-9A-F]{2}), 0x([0-9A-F]{2}), 0x([0-9A-F]{2}) \}, (MA_[MS]) \}", text):
        blocks[f"{a}:{b}:{c}"] = "IEEE MA-M BLOCK" if kind == "MA_M" else "IEEE MA-S BLOCK"
    table = text[text.index("global_manuf_oui24_table"):text.index("global_manuf_oui28_table")]
    for a, b, c, long_name in re.findall(
            r"\{ \{ 0x([0-9A-F]{2}), 0x([0-9A-F]{2}), 0x([0-9A-F]{2}) \}, \"[^\"]*\",\s*\"([^\"]*)\" \}", table):
        owners.setdefault(f"{a}:{b}:{c}", long_name)
    return blocks, owners


def parse_bluetooth(text, table):
    body = text[text.index(table):]
    body = body[:body.index("};")]
    return {k.upper(): v for k, v in re.findall(r"\{ 0x([0-9A-Fa-f]{4}),\s*\"([^\"]*)\" \}", body)}


def header(kind, commit, path, raw, today):
    return [
        f"# {kind}",
        f"# Generated by tools/refresh_registry_snapshots.py on {today}. Do not edit by hand.",
        f"# Source: https://github.com/{REPO}/blob/{commit}/{path}",
        f"# sha256 of that file: {hashlib.sha256(raw).hexdigest()}",
        "# Only identifiers used by src/lts/Signatures.h are listed. Tab separated.",
    ]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--manuf")
    ap.add_argument("--bluetooth")
    ap.add_argument("--commit")
    args = ap.parse_args()
    commit = args.commit or latest_commit()
    raw = "https://raw.githubusercontent.com/" + REPO + "/" + commit + "/"
    manuf = pathlib.Path(args.manuf).read_bytes() if args.manuf else fetch(raw + MANUF_PATH)
    bt = pathlib.Path(args.bluetooth).read_bytes() if args.bluetooth else fetch(raw + BT_PATH)
    today = datetime.date.today().isoformat()

    ouis, uuids, companies = used_identifiers()
    blocks, owners = parse_manuf(manuf.decode("utf-8"))
    uuid_owners = parse_bluetooth(bt.decode("utf-8"), "bluetooth_uuid_vals[]")
    company_owners = parse_bluetooth(bt.decode("utf-8"), "bluetooth_company_id_vals[]")

    OUT.mkdir(parents=True, exist_ok=True)
    lines = header("IEEE MA-L registry: address prefix owners", commit, MANUF_PATH, manuf, today)
    for oui in ouis:
        if int(oui[:2], 16) & 0x02:
            continue  # locally administered: no registry owner exists to check
        lines.append(f"{oui}\t{blocks.get(oui) or owners.get(oui) or 'UNASSIGNED'}")
    (OUT / "ieee_oui.tsv").write_text("\n".join(lines) + "\n", encoding="utf-8")

    lines = header("Bluetooth SIG 16-bit UUID owners", commit, BT_PATH, bt, today)
    lines += [f"{u}\t{uuid_owners.get(u, 'UNASSIGNED')}" for u in uuids]
    (OUT / "bt_sig_uuid16.tsv").write_text("\n".join(lines) + "\n", encoding="utf-8")

    lines = header("Bluetooth SIG company identifier owners", commit, BT_PATH, bt, today)
    lines += [f"{c}\t{company_owners.get(c, 'UNASSIGNED')}" for c in companies]
    (OUT / "bt_sig_company.tsv").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {len(ouis)} prefixes, {len(uuids)} UUIDs, {len(companies)} company IDs from {commit[:10]}")


if __name__ == "__main__":
    main()
